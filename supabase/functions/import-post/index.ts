// Import a single post into research_content so it can be torn down and
// reverse-engineered into a blueprint like any scraped post.
//
//   { url }                           → scrape that one post with the org's Apify
//                                       key (same actors as trigger-scrape), stored
//                                       exactly like a scraped post (source 'url').
//   { text, images?, platform?, ... } → a post pasted by hand (source 'paste').
//                                       `images` must already be permanent URLs
//                                       (the client uploads / rehosts them first).
//
// Optional organization_id (impersonation / agency client orgs).
// Returns { content_id, existing }.

import { createClient, type SupabaseClient } from 'https://esm.sh/@supabase/supabase-js@2.81.1';
import { assertOrgAccess } from '../_shared/org-access.ts';
import { authenticateRequest, unauthorized } from '../_shared/cli-auth.ts';
import { resolveApiKey } from '../_shared/resolve-api-key.ts';
import { decryptApiKey } from '../_shared/llm-client.ts';
import { sanitizeObject, transformContentItem } from '../_shared/research-content-transform.ts';
import { transcribeScrapedContent, type TranscriptRow } from '../_shared/scraped-transcript.ts';

const corsHeaders = {
  'Access-Control-Allow-Origin': '*',
  'Access-Control-Allow-Headers': 'authorization, x-client-info, apikey, content-type',
};

const json = (body: unknown, status = 200) =>
  new Response(JSON.stringify(body), { status, headers: { ...corsHeaders, 'Content-Type': 'application/json' } });

class ImportError extends Error {
  constructor(message: string, public status = 400) {
    super(message);
  }
}

type Platform = 'youtube' | 'tiktok' | 'instagram' | 'linkedin' | 'twitter';
const PASTE_PLATFORMS = ['youtube', 'tiktok', 'instagram', 'linkedin', 'twitter', 'other'];
const ACTOR_TIMEOUT_SECS = 110;

function detectPlatform(raw: string): Platform | null {
  let u: URL;
  try {
    u = new URL(raw);
  } catch {
    return null;
  }
  const host = u.hostname.toLowerCase().replace(/^(www|m|mobile)\./, '');
  const path = u.pathname;
  if (host === 'youtu.be' || (host.endsWith('youtube.com') && /^\/(watch|shorts\/|live\/)/.test(path))) return 'youtube';
  if (host.endsWith('tiktok.com') && /\/video\/|\/photo\/|^\/t\//.test(path)) return 'tiktok';
  if (host === 'vm.tiktok.com' || host === 'vt.tiktok.com') return 'tiktok';
  if (host.endsWith('instagram.com') && /^\/(p|reel|reels|tv)\//.test(path)) return 'instagram';
  if (host.endsWith('linkedin.com') && /^\/(posts|feed\/update|pulse)\//.test(path)) return 'linkedin';
  if ((host === 'x.com' || host.endsWith('twitter.com')) && /\/status\/\d+/.test(path)) return 'twitter';
  return null;
}

function actorFor(platform: Platform, url: string): { actor: string; input: Record<string, unknown> } {
  switch (platform) {
    case 'youtube':
      return {
        actor: 'streamers~youtube-scraper',
        input: {
          startUrls: [{ url }],
          maxResults: 1,
          maxResultsShorts: 1,
          downloadSubtitles: true,
          preferAutoGeneratedSubtitles: true,
          saveSubsToKVS: true,
          subtitlesFormat: 'plaintext',
          subtitlesLanguage: 'en',
        },
      };
    case 'tiktok':
      return {
        actor: 'clockworks~tiktok-scraper',
        input: {
          postURLs: [url],
          shouldDownloadSubtitles: true,
          shouldDownloadVideos: false,
          shouldDownloadCovers: false,
          shouldDownloadAvatars: false,
          shouldDownloadSlideshowImages: false,
        },
      };
    case 'instagram':
      // The profile post scraper trigger-scrape uses takes usernames; the general
      // scraper takes a post URL and returns the same item shape.
      return { actor: 'apify~instagram-scraper', input: { directUrls: [url], resultsType: 'posts', resultsLimit: 1 } };
    case 'linkedin':
      return { actor: 'supreme_coder~linkedin-post', input: { urls: [url], limitPerSource: 1 } };
    case 'twitter':
      return { actor: 'apidojo~tweet-scraper', input: { startUrls: [url], maxItems: 1 } };
  }
}

async function findExisting(supabase: SupabaseClient, orgId: string, urls: string[]) {
  const { data } = await supabase
    .from('research_content')
    .select('id')
    .eq('organization_id', orgId)
    .in('url', [...new Set(urls.filter(Boolean))])
    .limit(1)
    .maybeSingle();
  return data?.id as string | undefined;
}

async function importFromUrl(supabase: SupabaseClient, orgId: string, rawUrl: string) {
  const url = rawUrl.trim();
  const platform = detectPlatform(url);
  if (!platform) {
    throw new ImportError('Paste a link to a single YouTube video, TikTok, Instagram post/reel, LinkedIn post or X post.');
  }

  const already = await findExisting(supabase, orgId, [url]);
  if (already) return { content_id: already, existing: true };

  const key = await resolveApiKey(supabase, orgId, 'apify');
  if (!key) throw new ImportError('Add an Apify API key in Settings to import posts by link, or paste the post instead.');
  const apifyToken = await decryptApiKey(key.key_encrypted);

  const { actor, input } = actorFor(platform, url);
  const resp = await fetch(
    `https://api.apify.com/v2/acts/${actor}/run-sync-get-dataset-items?timeout=${ACTOR_TIMEOUT_SECS}&clean=true`,
    {
      method: 'POST',
      headers: { Authorization: `Bearer ${apifyToken}`, 'Content-Type': 'application/json' },
      body: JSON.stringify(input),
      signal: AbortSignal.timeout((ACTOR_TIMEOUT_SECS + 10) * 1000),
    },
  );
  if (!resp.ok) {
    const detail = (await resp.text()).slice(0, 300);
    console.error(`[import-post] ${actor} ${resp.status}: ${detail}`);
    throw new ImportError(
      resp.status === 408 ? 'The scraper timed out. Try again, or paste the post instead.' : `Couldn't fetch that post (Apify ${resp.status}).`,
      502,
    );
  }
  const items: any[] = await resp.json();
  const item = items.find((i) => i && !i.error && !i.errorDescription);
  if (!item) throw new ImportError("Couldn't read that post. It may be private or deleted; paste it instead.", 404);

  const row: Record<string, any> = sanitizeObject(transformContentItem(item, platform, 'url-import', orgId, null, null));
  row.url = row.url || url;
  row.source = 'url';
  // Carousel slides help the teardown read the visual format
  const slides = Array.isArray(item.images) ? item.images.filter((s: unknown) => typeof s === 'string') : [];
  if (slides.length) row.platform_data = { ...(row.platform_data || {}), images: slides.slice(0, 10) };

  // The actor may canonicalise the URL to one we already have (e.g. a creator scrape) — keep that row.
  const canonical = await findExisting(supabase, orgId, [row.url]);
  if (canonical) return { content_id: canonical, existing: true };

  const { data: inserted, error } = await supabase
    .from('research_content')
    .insert(row)
    .select('id, organization_id, platform, raw_data, duration_seconds, transcript, transcript_status')
    .single();
  if (error) throw new ImportError(`Failed to save post: ${error.message}`, 500);

  if ((platform === 'tiktok' || platform === 'instagram') && !inserted.transcript) {
    try {
      await transcribeScrapedContent(supabase, [inserted as TranscriptRow]);
    } catch (err) {
      console.error('[import-post] transcription failed:', err);
    }
  }
  return { content_id: inserted.id as string, existing: false };
}

async function importPasted(
  supabase: SupabaseClient,
  orgId: string,
  body: { text?: string; images?: unknown; platform?: string; author_name?: string; source_url?: string },
) {
  const text = (body.text || '').trim();
  const images = Array.isArray(body.images)
    ? body.images.filter((u): u is string => typeof u === 'string' && /^https:\/\//.test(u)).slice(0, 10)
    : [];
  if (!text && images.length === 0) throw new ImportError('Paste the post text or add at least one image.');
  if (text.length > 50_000) throw new ImportError('Post text is too long (50,000 characters max).');

  const sourceUrl = body.source_url?.trim();
  const platform = PASTE_PLATFORMS.includes(body.platform || '')
    ? body.platform!
    : (sourceUrl && detectPlatform(sourceUrl)) || 'other';
  const firstLine = text.split('\n').find((l) => l.trim())?.trim() || 'Pasted post';

  const { data, error } = await supabase
    .from('research_content')
    .insert({
      id: crypto.randomUUID(), // research_content.id has no DB default
      organization_id: orgId,
      platform,
      source: 'paste',
      // research_content is unique on (organization_id, url); a pasted post has none of its own
      url: sourceUrl && /^https?:\/\//.test(sourceUrl) ? sourceUrl : `paste:${crypto.randomUUID()}`,
      title: firstLine.slice(0, 200),
      description: text || null,
      thumbnail_url: images[0] || null,
      author_name: body.author_name?.trim() || null,
      platform_data: images.length ? { images } : {},
      raw_data: { pasted: true },
      engagement: {},
      published_at: new Date().toISOString(),
    })
    .select('id')
    .single();
  if (error) {
    if (error.code === '23505') throw new ImportError('That link is already in your Scraped Content.', 409);
    throw new ImportError(`Failed to save post: ${error.message}`, 500);
  }
  return { content_id: data.id as string, existing: false };
}

Deno.serve(async (req) => {
  if (req.method === 'OPTIONS') return new Response('ok', { headers: corsHeaders });

  const supabase = createClient(Deno.env.get('SUPABASE_URL')!, Deno.env.get('SUPABASE_SERVICE_ROLE_KEY')!);

  let body: Record<string, any>;
  try {
    body = await req.json();
  } catch {
    return json({ error: 'Invalid JSON body' }, 400);
  }

  let orgId: string;
  try {
    const caller = await authenticateRequest(req, supabase);
    orgId = body.organization_id || caller.organization_id;
    await assertOrgAccess(req, supabase, orgId);
  } catch (err) {
    return unauthorized(err, corsHeaders);
  }

  try {
    const result = body.url ? await importFromUrl(supabase, orgId, String(body.url)) : await importPasted(supabase, orgId, body);
    return json(result);
  } catch (err) {
    if (err instanceof ImportError) return json({ error: err.message }, err.status);
    console.error('[import-post]', err);
    return json({ error: err instanceof Error ? err.message : String(err) }, 500);
  }
});
