#!/usr/bin/env node
/**
 * build-skills.mjs
 *
 * Reads all skill .md files and inlines a SKILLS_MAP constant directly
 * into index.ts between sentinel comments. This avoids multi-file
 * import issues in Supabase edge function deployments.
 *
 * Run before deploying:
 *   npm run build:skills
 */

import { readFileSync, writeFileSync } from "fs";
import { join, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));

const REMOTION_RULES = [
  "animations",
  "videos",
  "audio",
  "sequencing",
  "transitions",
  "timing",
  "assets",
  "text-animations",
  "compositions",
];

const skillsMap = {};

for (const rule of REMOTION_RULES) {
  const path = join(__dirname, "skills", "remotion", `${rule}.md`);
  skillsMap[`remotion/${rule}`] = readFileSync(path, "utf-8");
  console.log(`  read remotion/${rule}.md (${skillsMap[`remotion/${rule}`].length} chars)`);
}

const catalogPath = join(__dirname, "skills", "compositions", "CATALOG.md");
skillsMap["compositions/CATALOG"] = readFileSync(catalogPath, "utf-8");
console.log(`  read compositions/CATALOG.md (${skillsMap["compositions/CATALOG"].length} chars)`);

// Build the inlined SKILLS_MAP block
const mapLines = [
  "// ── SKILLS_MAP (auto-generated by build-skills.mjs — do not edit) ──",
  "const SKILLS_MAP: Record<string, string> = {",
];
for (const [key, content] of Object.entries(skillsMap)) {
  const escaped = content.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
  mapLines.push(`  ${JSON.stringify(key)}: \`${escaped}\`,`);
  mapLines.push("");
}
mapLines.push("};");
const inlined = mapLines.join("\n");

// Patch index.ts between sentinel comments
const indexPath = join(__dirname, "index.ts");
let indexSrc = readFileSync(indexPath, "utf-8");

const START = "// @@SKILLS_MAP_START@@";
const END   = "// @@SKILLS_MAP_END@@";

if (!indexSrc.includes(START)) {
  console.error(`ERROR: Sentinel '${START}' not found in index.ts. Add it manually.`);
  process.exit(1);
}

const before = indexSrc.slice(0, indexSrc.indexOf(START));
const after  = indexSrc.slice(indexSrc.indexOf(END) + END.length);
indexSrc = `${before}${START}\n${inlined}\n${END}${after}`;

writeFileSync(indexPath, indexSrc, "utf-8");
console.log(`\nPatched index.ts (total ${indexSrc.length} chars)`);
