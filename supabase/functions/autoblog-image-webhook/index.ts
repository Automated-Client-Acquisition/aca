// Async hero-image completion webhook for the autoblog routine.
//
// The orchestrator fires a Replicate prediction with this URL as the webhook
// target. When the prediction completes, Replicate POSTs the prediction object
// here. We:
//   1. Persist the bytes via import-image-asset (Supabase storage +
//      library_saved_content).
//   2. Update hero_image_url on the blog_posts row in Supabase — zero rebuild,
//      the frontend reads it directly from the DB.
//
// Required secrets:
//   - SUPABASE_URL, SUPABASE_SERVICE_ROLE_KEY: standard.
//   - AUTOBLOG_WEBHOOK_SECRET: shared secret gating Replicate webhook calls.

import { createClient } from "npm:@supabase/supabase-js@^2";
import { requireEnv } from "../_shared/site-config.ts";

const corsHeaders = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
};

const IMPORT_ENDPOINT = `${requireEnv("SUPABASE_URL")}/functions/v1/import-image-asset`;

function jsonResp(body: unknown, status = 200) {
  return new Response(JSON.stringify(body), {
    status,
    headers: { ...corsHeaders, "Content-Type": "application/json" },
  });
}

function sanitizeSlug(slug: string): string {
  return slug
    .toLowerCase()
    .replace(/[^a-z0-9-]/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}

function extractOutputUrl(prediction: { output: unknown }): string | null {
  const out = prediction.output;
  if (!out) return null;
  if (typeof out === "string") return out;
  if (Array.isArray(out)) return out[0] ?? null;
  if (typeof out === "object" && out !== null && "url" in out) {
    const u = (out as { url: unknown }).url;
    return typeof u === "string" ? u : null;
  }
  return null;
}

async function persistImage(sourceUrl: string, slug: string): Promise<string> {
  const resp = await fetch(IMPORT_ENDPOINT, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      sourceUrl,
      slug,
      name: `Blog hero: ${slug}`,
      description: "Generated by autoblog routine, persisted via async webhook",
      tags: ["blog-hero", "autoblog"],
    }),
  });
  const data = await resp.json();
  if (!resp.ok) {
    throw new Error(`import-image-asset ${resp.status}: ${JSON.stringify(data)}`);
  }
  return data.permanentUrl as string;
}

Deno.serve(async (req) => {
  if (req.method === "OPTIONS") return new Response(null, { headers: corsHeaders });
  if (req.method !== "POST") return jsonResp({ error: "Method not allowed" }, 405);

  const url = new URL(req.url);
  const expectedSecret = Deno.env.get("AUTOBLOG_WEBHOOK_SECRET");
  if (expectedSecret) {
    if (url.searchParams.get("secret") !== expectedSecret) {
      return jsonResp({ error: "Invalid or missing webhook secret" }, 403);
    }
  }

  const slugParam = url.searchParams.get("slug");
  if (!slugParam) return jsonResp({ error: "Missing slug query param" }, 400);
  const slug = sanitizeSlug(slugParam);
  if (!slug) return jsonResp({ error: "slug param sanitized to empty" }, 400);

  let payload;
  try {
    payload = await req.json();
  } catch {
    return jsonResp({ error: "Invalid JSON body" }, 400);
  }

  if (payload.status !== "succeeded") {
    return jsonResp({
      ok: true,
      noop: true,
      reason: `prediction status=${payload.status}, ignoring`,
    });
  }

  const sourceUrl = extractOutputUrl(payload);
  if (!sourceUrl) {
    return jsonResp({ error: "No output URL in prediction", payload }, 400);
  }

  const supabaseUrl = Deno.env.get("SUPABASE_URL");
  const serviceRoleKey = Deno.env.get("SUPABASE_SERVICE_ROLE_KEY");
  if (!supabaseUrl || !serviceRoleKey) {
    return jsonResp({ error: "SUPABASE_URL or SUPABASE_SERVICE_ROLE_KEY not configured" }, 500);
  }

  try {
    // 1. Persist to Supabase storage + library_saved_content
    const permanentUrl = await persistImage(sourceUrl, slug);

    // 2. Update hero_image_url on the blog_posts row — no GitHub commit, no rebuild.
    const supabase = createClient(supabaseUrl, serviceRoleKey);
    const { error: dbError } = await supabase
      .from("blog_posts")
      .update({ hero_image_url: permanentUrl })
      .eq("slug", slug);

    if (dbError) {
      throw new Error(`DB update failed: ${dbError.message}`);
    }

    return jsonResp({ ok: true, slug, permanentUrl });
  } catch (err) {
    const message = err instanceof Error ? err.message : String(err);
    return jsonResp({ ok: false, error: message, slug }, 500);
  }
});
